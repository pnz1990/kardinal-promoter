// This file holds the SCM scenarios every git server suite runs. Each
// provider's file (scm_forgejo_test.go, scm_gitea_test.go, scm_gitlab_test.go,
// scm_github_test.go) runs them against its git server and claims its rows;
// the TestSCM_ tests here run in every suite.

// The headers /webhook/scm reads a signature from, in the order it looks for
// them (cmd/kardinal-controller/webhook.go).
const (
	hubSignature     = "X-Hub-Signature-256"
	giteaSignature   = "X-Gitea-Signature"
	forgejoSignature = "X-Forgejo-Signature"
	gitlabToken      = "X-Gitlab-Token"
)

// envSCMAPI is the git server's API URL as the controller reaches it, which
// hack/e2e/up.sh passes as --scm-api-url (unset on GitHub).
const envSCMAPI = "KARDINAL_E2E_SCM_API"

// fakeToken is a token no git server accepts. It is not a secret.
const fakeToken = "kardinal-e2e-not-a-token"

// prBodyFooter ends every PR body (pkg/scm/pr_template.go).
const prBodyFooter = "---\n*Generated by [kardinal-promoter](https://github.com/pnz1990/kardinal-promoter)*"

// Rows of the PR body (pkg/scm/pr_template.go).
var (
	evaluatedAt = `\d{4}-\d\d-\d\dT\d\d:\d\dZ`
	upstreamRow = regexp.MustCompile(`\| test \| ` + evaluatedAt + ` \| \d+m \|`)
)

// requireKind fails a provider test run against another suite's git server.
func requireKind(t *testing.T, e *framework.Env, kind string) {
	t.Helper()
	if got := e.Git.Kind(); got != kind {
		t.Fatalf("this test is for %s; the suite's git server is %s (check the suite's RUN pattern)", kind, got)
	}
}

// waitOpenPR waits until bundle's env step waits for its PR and returns the
// step and the open PR.
func (a *app) waitOpenPR(t *testing.T, bundle, env string) (*v1alpha1.PromotionStep, gitserver.PR) {
	t.Helper()
	ps := a.e.WaitStepState(t, a.ns, pipelineName, bundle, env, "WaitingForMerge", promoteTimeout)
	return ps, a.openPR(t, bundle, env)
}

// rerunOpenPR rewinds a step that waits for its PR to open-pr, as if the
// controller had crashed before saving the PR, and waits until open-pr ran
// again and the step waits for a PR again.
func (a *app) rerunOpenPR(t *testing.T, ps *v1alpha1.PromotionStep, bundle, env string) *v1alpha1.PromotionStep {
	t.Helper()
	rewound := time.Now().Truncate(time.Second)
	idx := a.e.RewindToOpenPR(t, ps)
	return a.e.WaitStep(t, a.ns, pipelineName, bundle, env, 2*time.Minute, "open-pr to run again",
		func(ps *v1alpha1.PromotionStep) (bool, string) {
			if len(ps.Status.Steps) <= idx {
				return false, fmt.Sprintf("%d steps", len(ps.Status.Steps))
			}
			s := ps.Status.Steps[idx]
			done := s.CompletedAt != nil && !s.CompletedAt.Time.Before(rewound)
			return done && ps.Status.State == "WaitingForMerge",
				fmt.Sprintf("state=%q open-pr=%s message=%q", ps.Status.State, s.State, ps.Status.Message)
		})
}

