// kindSignature is the header the git server of kind signs its webhook
// deliveries in.
func kindSignature(kind string) string {
	switch kind {
	case "gitlab":
		return gitlabToken
	case "github":
		return hubSignature
	case "gitea":
		return giteaSignature
	}
	return forgejoSignature
}

// eventHeader is the event header that goes with signature header sig.
func eventHeader(sig string) string {
	switch sig {
	case gitlabToken:
		return "X-Gitlab-Event"
	case hubSignature:
		return "X-GitHub-Event"
	case giteaSignature:
		return "X-Gitea-Event"
	}
	return "X-Forgejo-Event"
}

// prEvent is the pull request event name in eventHeader(sig).
func prEvent(sig string) string {
	if sig == gitlabToken {
		return "Merge Request Hook"
	}
	return "pull_request"
}

// signature is header sig's value for body: GitLab's plaintext token, GitHub's
// "sha256=" HMAC, or the hex HMAC of Gitea and Forgejo.
func signature(sig, secret string, body []byte) string {
	switch sig {
	case gitlabToken:
		return secret
	case hubSignature:
		return "sha256=" + framework.HMACHex(secret, body)
	}
	return framework.HMACHex(secret, body)
}

// signedPREvent are the headers of a pull request event signed with secret
// in sig.
func signedPREvent(sig, secret string, body []byte) map[string]string {
	return map[string]string{sig: signature(sig, secret, body), eventHeader(sig): prEvent(sig)}
}

// forgejoEvent is a Forgejo/Gitea pull request event body.
func forgejoEvent(t *testing.T, repo string, number int, action string, merged bool, state string) []byte {
	t.Helper()
	return framework.JSONBody(t, map[string]interface{}{
		"action": action,
		"number": number,
		"pull_request": map[string]interface{}{
			"number": number, "merged": merged, "state": state,
		},
		"repository": map[string]interface{}{"full_name": repo},
	})
}

// mergedEvent is the body kind's git server sends when PR number of repo
// is merged; sha is the merge commit the event carries, "" for an event
// without one (a GitLab fast-forward merge).
func mergedEvent(t *testing.T, kind, repo string, number int, sha string) []byte {
	t.Helper()
	switch kind {
	case "gitlab":
		return framework.JSONBody(t, map[string]interface{}{
			"object_kind": "merge_request",
			"object_attributes": map[string]interface{}{
				"iid": number, "state": "merged", "action": "merge", "merge_commit_sha": sha,
			},
			"project": map[string]interface{}{"path_with_namespace": repo},
		})
	case "github":
		return framework.JSONBody(t, map[string]interface{}{
			"action":       "closed",
			"pull_request": map[string]interface{}{"number": number, "merged": true, "merge_commit_sha": sha},
			"repository":   map[string]interface{}{"full_name": repo},
		})
	}
	if sha == "" {
		return forgejoEvent(t, repo, number, "closed", true, "closed")
	}
	return framework.JSONBody(t, map[string]interface{}{
		"action": "closed",
		"number": number,
		"pull_request": map[string]interface{}{
			"number": number, "merged": true, "state": "closed", "merge_commit_sha": sha,
		},
		"repository": map[string]interface{}{"full_name": repo},
	})
}

// mergeSeenByWebhook merges pr right after the PRStatus reconciler polled it,
// has deliver post the merge event (nil: the git server's own webhook
// delivers it), and returns the controller's "marked merged via webhook" line.
// The next poll is about 30s away, so the line, with no poll that saw the
// merge before it, shows the webhook told the controller.
func (a *app) mergeSeenByWebhook(t *testing.T, ps *v1alpha1.PromotionStep, pr gitserver.PR,
	deliver func(*v1alpha1.PRStatus)) framework.LogLine {
	t.Helper()
	var prs *v1alpha1.PRStatus
	framework.Eventually(t, time.Minute, fmt.Sprintf("the PRStatus to poll PR #%d", pr.Number), func(ctx context.Context) (bool, string) {
		p, err := a.e.PRStatusOf(ctx, ps)
		if err != nil {
			return false, err.Error()
		}
		prs = p
		return p.Spec.PRNumber == pr.Number && p.Status.LastCheckedAt != nil, framework.DescribePRStatus(p)
	})
	ref := prs.Name
	polled := framework.LogMessage("PR still open, requeueing", "prstatus", ref, "namespace", a.ns)
	a.e.ControllerLog(time.Now().Add(-40*time.Second)).Wait(t, time.Minute, "a poll of "+ref+" in the last 10s",
		func(l framework.LogLine) bool { return polled(l) && time.Since(l.At) < 10*time.Second })

	since := time.Now()
	a.merge(t, pr)
	if deliver != nil {
		deliver(prs)
	}
	mark := a.e.WaitControllerLog(t, since, 25*time.Second, "the webhook to mark "+ref+" merged",
		framework.LogMessage("PRStatus marked merged via webhook", "prstatus", ref, "namespace", a.ns, "pr", strconv.Itoa(pr.Number)))
	received := framework.LogMessage("webhook received", "pr", strconv.Itoa(pr.Number), "merged", "true")
	a.e.WaitControllerLog(t, since, 5*time.Second, "the merge event of "+prs.Spec.Repo+" logged with its repo",
		func(l framework.LogLine) bool { return received(l) && strings.EqualFold(l.Str("repo"), prs.Spec.Repo) })
	for _, l := range a.e.ControllerLogLines(t, since, framework.LogMessage("PR merged — status updated", "prstatus", ref, "namespace", a.ns)) {
		assert.False(t, l.At.Before(mark.At), "a poll saw the merge before the webhook: %s", l)
	}
	return mark
}

// mergeByWebhook merges bundle's env PR and checks that the webhook told the
// controller: header "" relies on the git server's own delivery; otherwise
// the test posts the merge event signed in header. eventSHA says whether the
// event carries the merge commit; when it does not, the PRStatus reconciler
// asks the git server for it. The step then reaches Verified with the merge
// commit as the revision it checked.
func (a *app) mergeByWebhook(t *testing.T, bundle, env, header string, eventSHA bool) {
	t.Helper()
	ps, pr := a.waitOpenPR(t, bundle, env)
	var deliver func(*v1alpha1.PRStatus)
	if header != "" {
		deliver = func(prs *v1alpha1.PRStatus) {
			sha := ""
			if eventSHA {
				sha = a.e.WaitPRState(t, a.repo, pr.Number, "merged", 30*time.Second).MergeCommit
			}
			body := mergedEvent(t, a.e.Git.Kind(), prs.Spec.Repo, pr.Number, sha)
			code := a.e.PostSCMWebhook(t, signedPREvent(header, framework.WebhookSecret(t), body), body)
			require.Equal(t, http.StatusNoContent, code, "the merge event signed in %s", header)
		}
	}
	mark := a.mergeSeenByWebhook(t, ps, pr, deliver)

	merged := a.e.WaitPRState(t, a.repo, pr.Number, "merged", 30*time.Second)
	require.NotEmpty(t, merged.MergeCommit, "the git server reports PR #%d's merge commit", pr.Number)
	if eventSHA {
		assert.Equal(t, merged.MergeCommit, mark.Str("mergeCommit"), "the webhook records the event's merge commit")
	} else {
		assert.Empty(t, mark.Str("mergeCommit"), "the event carries no merge commit")
	}
	prs := a.e.WaitPRStatus(t, a.ns, pipelineName, bundle, env, time.Minute, "merged with its merge commit",
		func(p *v1alpha1.PRStatus) bool { return p.Status.Merged && p.Status.MergeCommitSHA != "" })
	assert.Equal(t, merged.MergeCommit, prs.Status.MergeCommitSHA)
	done := a.e.WaitStepState(t, a.ns, pipelineName, bundle, env, "Verified", promoteTimeout)
	assert.Equal(t, merged.MergeCommit, done.Status.Outputs["mergeCommitSHA"], "the revision the health check expected")
}

// stillOpen checks for d that bundle's env step still waits for its PR and
// the PRStatus still records it open and not merged.
func (a *app) stillOpen(t *testing.T, bundle, env string, d time.Duration, why string) {
	t.Helper()
	framework.Consistently(t, d, why+": the step waits for the open PR", func(context.Context) (bool, string) {
		// Not the poll context, which ends at the deadline.
		ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cancel()
		ps, ok, err := a.e.Step(ctx, a.ns, pipelineName, bundle, env)
		if err != nil || !ok {
			return false, fmt.Sprintf("step: ok=%v err=%v", ok, err)
		}
		prs, err := a.e.PRStatusOf(ctx, ps)
		if err != nil {
			return false, err.Error()
		}
		return ps.Status.State == "WaitingForMerge" && prs.Status.Open && !prs.Status.Merged,
			fmt.Sprintf("state=%q %s", ps.Status.State, framework.DescribePRStatus(prs))
	})
}

// prBody is a PR body with the line endings the template wrote (GitLab
// returns CRLF) and without the trailing newline.
func prBody(raw string) string {
	return strings.TrimSpace(strings.ReplaceAll(raw, "\r\n", "\n"))
}

// scmPromotionPR checks the PR a pr-review environment opens, then reruns
// open-pr and checks it finds that PR instead of opening another. edit, when
// set, changes the Pipeline first.
func scmPromotionPR(t *testing.T, e *framework.Env, edit func(*v1alpha1.Pipeline)) {
	t.Helper()
	a := newArgoApp(t, e, "test", "prod")
	e.CreateGate(t, framework.Gate(a.ns, "always", "prod", "true", recheck))
	p := a.pipeline(map[string]string{"prod": "pr-review"})
	if edit != nil {
		edit(p)
	}
	a.apply(t, p)

	bundle := e.CreateBundle(t, a.ns, pipelineName, "--image", imageV2)
	e.WaitStepState(t, a.ns, pipelineName, bundle, "test", "Verified", promoteTimeout)
	ps, pr := a.waitOpenPR(t, bundle, "prod")

	assert.Equal(t, "[kardinal] Promote "+bundle+" to prod", pr.Title)
	assert.Equal(t, prHead(bundle, "prod"), pr.Head)
	assert.Equal(t, a.repo.Branch, pr.Base)
	assert.Subset(t, pr.Labels, []string{"kardinal", "kardinal/promotion"})
	assert.NotContains(t, pr.Labels, "kardinal/rollback")
	body := prBody(pr.Body)
	assert.True(t, strings.HasPrefix(body, "<!-- kardinal-promoter auto-generated PR -->\n## Promotion: "+bundle+" -> podinfo/prod\n"),
		"body starts with the promotion heading:\n%s", body)
	assert.Contains(t, body, "| "+fixtures.Image+" | "+fixtures.V2+" | — | — | — | — |", "artifact row")
	assert.Regexp(t, `\| always \| `+regexp.QuoteMeta(a.ns)+` \| Pass \| bundle\.version=`+regexp.QuoteMeta(fixtures.V2)+
		`: true = true \| `+evaluatedAt+` \|`, body, "gate row")
	assert.Regexp(t, upstreamRow, body, "upstream row")
	assert.True(t, strings.HasSuffix(body, prBodyFooter), "body ends with the footer:\n%s", body)

	ps = a.rerunOpenPR(t, ps, bundle, "prod")
	assert.Equal(t, strconv.Itoa(pr.Number), ps.Status.Outputs["prNumber"], "open-pr found PR #%d again", pr.Number)
	prs, err := e.Git.PullRequests(context.Background(), a.repo)
	require.NoError(t, err)
	var same []string
	for _, p := range prs {
		if p.Head == pr.Head {
			same = append(same, fmt.Sprintf("#%d %s", p.Number, p.State))
		}
	}
	assert.Equal(t, []string{fmt.Sprintf("#%d open", pr.Number)}, same, "PRs from %s", pr.Head)

	a.merge(t, pr)
	e.WaitStepState(t, a.ns, pipelineName, bundle, "prod", "Verified", promoteTimeout)
	assertEnvAt(t, a, "prod", fixtures.V2)
}

// scmMergeByPolling merges a PR on a repo without the webhook and checks the
// PRStatus poll finds the merge and its commit within one interval, and the
// step goes on to HealthChecking and Verified with that commit. check, when
// set, runs while the PR is open.
func scmMergeByPolling(t *testing.T, e *framework.Env, check func(a *app, bundle string, ps *v1alpha1.PromotionStep, pr gitserver.PR)) {
	t.Helper()
	a := newArgoAppIn(t, e, e.RepoWithoutWebhook, "test", "prod")
	a.apply(t, a.pipeline(map[string]string{"prod": "pr-review"}))
	bundle := e.CreateBundle(t, a.ns, pipelineName, "--image", imageV2)
	ps, pr := a.waitOpenPR(t, bundle, "prod")
	if check != nil {
		check(a, bundle, ps, pr)
	}

	ref := ps.Spec.PRStatusRef
	since := time.Now()
	a.merge(t, pr)
	polled := e.WaitControllerLog(t, since, 90*time.Second, "the poll that finds PR #"+strconv.Itoa(pr.Number)+" merged",
		framework.LogMessage("PR merged — status updated", "prstatus", ref, "namespace", a.ns))
	assert.WithinDuration(t, since, polled.At, 45*time.Second, "PRStatus polls an open PR every 30s")
	e.WaitControllerLog(t, since, time.Minute, "the step to leave WaitingForMerge",
		framework.LogMessage("PRStatus reports merged — advancing to HealthChecking", "prStatusRef", ref))

	merged := e.WaitPRState(t, a.repo, pr.Number, "merged", 30*time.Second)
	require.NotEmpty(t, merged.MergeCommit)
	assert.Equal(t, merged.MergeCommit, polled.Str("mergeCommit"), "the poll records the merge commit")
	done := e.WaitStepState(t, a.ns, pipelineName, bundle, "prod", "Verified", promoteTimeout)
	prs, err := e.PRStatusOf(context.Background(), done)
	require.NoError(t, err)
	assert.True(t, prs.Status.Merged)
	assert.Equal(t, merged.MergeCommit, prs.Status.MergeCommitSHA)
	assert.Equal(t, merged.MergeCommit, done.Status.Outputs["mergeCommitSHA"], "the revision the health check expected")
	assert.Empty(t, e.ControllerLogLines(t, since, framework.LogMessage("PRStatus marked merged via webhook", "prstatus", ref)),
		"the repo has no webhook")
	assertEnvAt(t, a, "prod", fixtures.V2)
}

// scmBadSignature opens a PR, posts its merge event with a wrong signature
// and without one in each of headers, and checks each is refused with 401
// and changes nothing. The same event for another repo, signed right, is
// accepted, so the 401s are the signature's. It returns the app with the PR
// still open, and its PRStatus.
func scmBadSignature(t *testing.T, e *framework.Env, headers ...string) (*app, string, gitserver.PR, *v1alpha1.PRStatus) {
	t.Helper()
	a, bundle, pr, prs := prOpenWithoutWebhook(t, e)
	kind := e.Git.Kind()
	secret := framework.WebhookSecret(t)
	body := mergedEvent(t, kind, prs.Spec.Repo, pr.Number, pr.HeadSHA)
	for i, h := range headers {
		assert.Equal(t, http.StatusUnauthorized, e.PostSCMWebhook(t, signedPREvent(h, "not-the-secret", body), body),
			"%s signed with another secret", h)
		assert.Equal(t, http.StatusUnauthorized, e.PostSCMWebhook(t, map[string]string{eventHeader(h): prEvent(h)}, body),
			"no %s", h)
		control := mergedEvent(t, kind, "e2e/no-such-repo", 900000+100*pr.Number+i, pr.HeadSHA)
		assert.Equal(t, http.StatusNoContent, e.PostSCMWebhook(t, signedPREvent(h, secret, control), control),
			"another repo's merge event signed right in %s", h)
	}
	a.stillOpen(t, bundle, "prod", 10*time.Second, "after the refused merge events")
	return a, bundle, pr, prs
}

