// scmLabels checks the PR labels on a promotion and a rollback: a promotion
// PR gets kardinal and kardinal/promotion, and the PR of a `kardinal
// rollback` gets kardinal/rollback too, with the rollback title and body. It
// merges every PR and returns the app, whose prod runs fixtures.V2.
func scmLabels(t *testing.T, e *framework.Env) *app {
	t.Helper()
	a := newArgoApp(t, e, "prod")
	a.apply(t, a.pipeline(map[string]string{"prod": "pr-review"}))
	labels := []string{"kardinal", "kardinal/promotion"}

	first := e.CreateBundle(t, a.ns, pipelineName, "--image", imageV2)
	_, pr := a.waitOpenPR(t, first, "prod")
	assert.Subset(t, pr.Labels, labels)
	assert.NotContains(t, pr.Labels, "kardinal/rollback")
	a.merge(t, pr)
	e.WaitStepState(t, a.ns, pipelineName, first, "prod", "Verified", promoteTimeout)
	second := e.CreateBundle(t, a.ns, pipelineName, "--image", imageV3)
	_, pr = a.waitOpenPR(t, second, "prod")
	a.merge(t, pr)
	e.WaitStepState(t, a.ns, pipelineName, second, "prod", "Verified", promoteTimeout)

	out := e.MustKardinal(t, a.ns, "rollback", pipelineName, "--env", "prod")
	m := regexp.MustCompile(`Bundle (\S+) created \(rollbackOf=(\S+)\)`).FindStringSubmatch(out)
	require.NotNil(t, m, "rollback output:\n%s", out)
	rollback := m[1]
	require.Equal(t, first, m[2], "rolls back to the Bundle before %s", second)
	_, pr = a.waitOpenPR(t, rollback, "prod")
	assert.Equal(t, "[kardinal] Rollback prod to "+rollback+" (restores "+fixtures.V2+")", pr.Title)
	assert.Subset(t, pr.Labels, append(labels, "kardinal/rollback"))
	body := prBody(pr.Body)
	assert.True(t, strings.HasPrefix(body, "<!-- kardinal-promoter auto-generated PR -->\n## ROLLBACK: "+rollback+" -> podinfo/prod\n\n"+
		"> **This is a rollback PR.** It restores the images of bundle "+first+" in environment prod.\n"+
		"> Rolling back FROM: "+second+" ("+fixtures.V3+")\n"+
		"> Rolling back TO: "+first+" ("+fixtures.V2+")\n"+
		"> Rolled back by: "+cliUser(t)+"\n"), "rollback body:\n%s", body)
	a.merge(t, pr)
	e.WaitStepState(t, a.ns, pipelineName, rollback, "prod", "Verified", promoteTimeout)
	assertEnvAt(t, a, "prod", fixtures.V2)
	return a
}

// scmLabelsAndRotation checks the PR labels on a promotion and a rollback
// (scmLabels), then rotates the token to a git user that may push and open
// PRs but not label them: the running controller picks the new token up from
// the Secret without a restart, opens the next PR as that user, and leaves it
// open without labels. The test must not be parallel: it changes the
// controller's token.
func scmLabelsAndRotation(t *testing.T, e *framework.Env, scopes []string) {
	t.Helper()
	a := scmLabels(t, e)

	// The new token's user may push and open PRs but not label them.
	user := "rot-" + a.ns[len(a.ns)-8:]
	tok := e.GitUser(t, user, scopes)
	require.NoError(t, e.GitUsers(t).AddCollaborator(context.Background(), a.repo, user))
	pod := e.ControllerPod(t).Name
	since := time.Now()
	restoreSCM := e.SetSecretValue(t, framework.ControllerNamespace, framework.GitSecretName, "token", []byte(tok))
	restoreGit := e.SetSecretValue(t, a.ns, framework.GitSecretName, "token", []byte(tok))
	rotated := framework.LogMessage("SCM credentials rotated", "secret", framework.ControllerNamespace+"/"+framework.GitSecretName, "key", "token")
	e.WaitControllerLog(t, since, 50*time.Second, "the controller to load the new token", rotated)
	assert.Equal(t, pod, e.ControllerPod(t).Name, "no restart")

	fourth := e.CreateBundle(t, a.ns, pipelineName, "--image", imageV3)
	_, pr := a.waitOpenPR(t, fourth, "prod")
	assert.Equal(t, user, pr.Author, "the PR is opened with the new token")
	assert.Empty(t, pr.Labels, "the new token may not label PRs")
	e.WaitControllerLog(t, since, time.Minute, "the label failure",
		framework.LogMessage("add PR labels failed", "pr", strconv.Itoa(pr.Number)))
	// The step message records the failure while the step waits for the merge
	// (docs/pr-evidence.md), and status.outputs.prLabelsError keeps it.
	want := fmt.Sprintf("PR #%d is open, waiting for merge; adding labels failed: ", pr.Number)
	ps := e.WaitStep(t, a.ns, pipelineName, fourth, "prod", time.Minute, "the label failure in its message",
		func(s *v1alpha1.PromotionStep) (bool, string) {
			return s.Status.State == "WaitingForMerge" && strings.HasPrefix(s.Status.Message, want),
				fmt.Sprintf("state=%q message=%q", s.Status.State, s.Status.Message)
		})
	assert.NotEmpty(t, ps.Status.Outputs["prLabelsError"], "status.outputs.prLabelsError")
	a.stillOpen(t, fourth, "prod", 10*time.Second, "after the label failure")

	since = time.Now()
	restoreSCM()
	restoreGit()
	e.WaitControllerLog(t, since, 50*time.Second, "the controller to load the old token again", rotated)
	a.merge(t, pr)
	e.WaitStepState(t, a.ns, pipelineName, fourth, "prod", "Verified", promoteTimeout)
	assertEnvAt(t, a, "prod", fixtures.V3)
}

// TestSCM_DeletedStepTracksItsNewPR deletes, on its own, the prod
// PromotionStep of a Bundle waiting for its PR. The controller closes that PR
// with a comment, kro creates the step again, and the new step opens a new PR.
// Its PRStatus kept naming the old PR, so the controller polled the closed PR,
// never saw a merge of the new one, and failed the new step when the 5-minute
// grace window ended (B72). Now the PRStatus names the new PR, with a status
// written for it, and merging the new PR promotes prod. The new PR is opened
// from the same branch about a second after the delete; the controller deleted
// that branch with the old PR, and Forgejo and Gitea close every open PR of a
// deleted branch from a queue after the delete returns, so they closed the new
// PR too (B79). The controller keeps the branch now, and the new PR stays open
// until it is merged.
//
// Covers STEP-DELETE-PR-04.
func TestSCM_DeletedStepTracksItsNewPR(t *testing.T) {
	t.Parallel()
	e := framework.New(t)
	ctx := context.Background()
	a := newArgoApp(t, e, "prod")
	a.apply(t, a.pipeline(map[string]string{"prod": "pr-review"}))
	bundle := e.CreateBundle(t, a.ns, pipelineName, "--image", imageV2)
	old, pr := a.waitOpenPR(t, bundle, "prod")
	require.Contains(t, old.Finalizers, closePRFinalizer, "the step closes its PR when it is deleted")
	e.WaitPRStatus(t, a.ns, pipelineName, bundle, "prod", time.Minute, fmt.Sprintf("tracking PR #%d", pr.Number),
		func(p *v1alpha1.PRStatus) bool { return p.Spec.PRNumber == pr.Number && p.Status.Open })

	require.NoError(t, e.Client.Delete(ctx, old))
	e.WaitPRState(t, a.repo, pr.Number, "closed", 2*time.Minute)
	oneComment(t, a, pr.Number, "kardinal closed this PR: PromotionStep "+old.Name+" was deleted")

	e.WaitStep(t, a.ns, pipelineName, bundle, "prod", promoteTimeout, "the recreated step waiting for a new PR",
		func(s *v1alpha1.PromotionStep) (bool, string) {
			return s.UID != old.UID && s.Status.State == "WaitingForMerge",
				fmt.Sprintf("uid=%s state=%q message=%q", s.UID, s.Status.State, s.Status.Message)
		})
	again := a.openPR(t, bundle, "prod")
	require.NotEqual(t, pr.Number, again.Number, "the recreated step opened a new PR")
	require.Equal(t, pr.Head, again.Head, "the new PR is from the old PR's branch")
	e.WaitPRStatus(t, a.ns, pipelineName, bundle, "prod", time.Minute, fmt.Sprintf("tracking the new PR #%d", again.Number),
		func(p *v1alpha1.PRStatus) bool {
			return p.Spec.PRNumber == again.Number && p.Status.ObservedGeneration == p.Generation &&
				p.Status.Open && !p.Status.ClosedFinal && p.Status.ClosedAt == nil
		})

	a.merge(t, again)
	e.WaitStepState(t, a.ns, pipelineName, bundle, "prod", "Verified", promoteTimeout)
	assertEnvAt(t, a, "prod", fixtures.V2)
}

// TestSCM_WebhookMergeIsConfirmed posts a merge event, signed with the
// webhook secret, for a PR that is still open. The controller asks the git
// server whether the PR is merged, so the PRStatus is not marked merged and
// the step keeps waiting; any validly signed merge event used to advance the
// step without a merge (B73). The same event signed wrong, and unsigned, is
// refused and logged with the header its signature was read from and the
// sender's address (B76). Once the PR is merged, the event is confirmed and
// marks it merged, logged with its repo and the PRStatus namespace.
//
// Covers WEBHOOK-CONFIRM-01, WEBHOOK-LOG-01.
func TestSCM_WebhookMergeIsConfirmed(t *testing.T) {
	t.Parallel()
	e := framework.New(t)
	a, bundle, pr, prs := prOpenWithoutWebhook(t, e)
	kind := e.Git.Kind()
	sig := kindSignature(kind)
	body := mergedEvent(t, kind, prs.Spec.Repo, pr.Number, pr.HeadSHA)
	since := time.Now()
	require.Equal(t, http.StatusNoContent, e.PostSCMWebhook(t, signedPREvent(sig, framework.WebhookSecret(t), body), body),
		"the merge event of the open PR, signed in %s", sig)
	e.WaitControllerLog(t, since, 30*time.Second, "the git server reporting PR #"+strconv.Itoa(pr.Number)+" open",
		framework.LogMessage("SCM provider reports the PR of the merge event not merged; PRStatus not marked merged",
			"prstatus", prs.Name, "namespace", a.ns, "repo", prs.Spec.Repo, "pr", strconv.Itoa(pr.Number), "open", "true"))
	a.stillOpen(t, bundle, "prod", 15*time.Second, "after the merge event of the open PR")
	assert.Empty(t, e.ControllerLogLines(t, since, framework.LogMessage("PRStatus marked merged via webhook", "prstatus", prs.Name)))

	for _, c := range []struct {
		header, logged string
		headers        map[string]string
	}{
		{sig, sig, signedPREvent(sig, "not-the-secret", body)},
		{"no signature", "none", map[string]string{eventHeader(sig): prEvent(sig)}},
	} {
		since := time.Now()
		require.Equal(t, http.StatusUnauthorized, e.PostSCMWebhook(t, c.headers, body), "the merge event, %s", c.header)
		l := e.WaitControllerLog(t, since, 30*time.Second, "the refused event logged with signatureHeader "+c.logged,
			framework.LogMessage("webhook signature invalid or parse error", "signatureHeader", c.logged))
		assert.NotEmpty(t, l.Str("remoteAddr"), "the sender of the refused event: %s", l)
	}

	// Signed right once the PR is merged, the event is confirmed and marks
	// the PRStatus merged (mergeSeenByWebhook checks the logged repo and
	// namespace).
	a.mergeByWebhook(t, bundle, "prod", sig, true)
	assertEnvAt(t, a, "prod", fixtures.V2)
}

// TestSCM_DuplicatePRReusesSameBase checks which PR open-pr adopts when the
// git server refuses a duplicate: with the promotion PR open and a second PR
// from the same branch into another base, a rerun of open-pr finds the PR
// into the Pipeline's branch and never the other one, and opens nothing new.
//
// Covers SCM-OTHERBASE-01.
func TestSCM_DuplicatePRReusesSameBase(t *testing.T) {
	t.Parallel()
	e := framework.New(t)
	a := newArgoApp(t, e, "prod")
	a.apply(t, a.pipeline(map[string]string{"prod": "pr-review"}))
	bundle := e.CreateBundle(t, a.ns, pipelineName, "--image", imageV2)
	ps, pr := a.waitOpenPR(t, bundle, "prod")

	other := a.repo
	other.Branch = a.repo.Branch + "-other"
	e.GitBranch(t, a.repo, other.Branch, a.repo.Branch)
	ctx := context.Background()
	stray, err := e.Brancher(t).OpenPR(ctx, a.repo, pr.Head, other.Branch, "e2e: the same head into another base")
	require.NoError(t, err)
	t.Cleanup(func() { _ = e.Git.ClosePR(context.Background(), other, stray.Number) })
	t.Logf("PR #%d from %s into %s", stray.Number, pr.Head, other.Branch)

	ps = a.rerunOpenPR(t, ps, bundle, "prod")
	assert.Equal(t, strconv.Itoa(pr.Number), ps.Status.Outputs["prNumber"],
		"open-pr adopts PR #%d into %s, not #%d into %s", pr.Number, a.repo.Branch, stray.Number, other.Branch)
	assert.True(t, strings.HasSuffix(ps.Status.PRURL, "/"+strconv.Itoa(pr.Number)), "prURL %s", ps.Status.PRURL)

	prs, err := e.Git.PullRequests(ctx, a.repo)
	require.NoError(t, err)
	var into []string
	for _, p := range prs {
		if p.Head == pr.Head {
			into = append(into, fmt.Sprintf("#%d %s", p.Number, p.State))
		}
	}
	assert.Equal(t, []string{fmt.Sprintf("#%d open", pr.Number)}, into, "PRs from %s into %s", pr.Head, a.repo.Branch)
	prs, err = e.Git.PullRequests(ctx, other)
	require.NoError(t, err)
	var stays []string
	for _, p := range prs {
		stays = append(stays, fmt.Sprintf("#%d %s", p.Number, p.State))
	}
	assert.Equal(t, []string{fmt.Sprintf("#%d open", stray.Number)}, stays, "PRs into %s", other.Branch)

	require.NoError(t, e.Git.ClosePR(ctx, other, stray.Number))
	a.merge(t, pr)
	e.WaitStepState(t, a.ns, pipelineName, bundle, "prod", "Verified", promoteTimeout)
	assertEnvAt(t, a, "prod", fixtures.V2)
}

// TestSCM_KardinalClosedPRGetsOneComment: a prod PR not merged within
// waitForMergeTimeout is closed by kardinal, with one comment saying why. Its
// Bundle fails and keeps its Graph, so the PRStatus keeps polling the closed
// PR. When the 5-minute grace window ends, the PRStatus reconciler used to
// post a second comment, "kardinal stopped tracking this PR", which is meant
// for a PR a person closed (#1351). The close marks the PRStatus with the PR
// number (kardinal.io/closed-by-kardinal), so the PR keeps its one comment
// after the window: the PRStatus is final-closed and has no second comment.
//
// Covers SCM-CLOSED-02.
func TestSCM_KardinalClosedPRGetsOneComment(t *testing.T) {
	t.Parallel()
	e := framework.New(t)
	a := newArgoApp(t, e, "prod")
	p := a.pipeline(map[string]string{"prod": "pr-review"})
	envSpec(t, p, "prod").WaitForMergeTimeout = "60s"
	a.apply(t, p)

	bundle := e.CreateBundle(t, a.ns, pipelineName, "--image", imageV2)
	_, pr := a.waitOpenPR(t, bundle, "prod")
	ps := e.WaitStepState(t, a.ns, pipelineName, bundle, "prod", "Failed", 3*time.Minute)
	assert.Contains(t, ps.Status.Message, "wait-for-merge timeout after 1m0s")
	e.WaitPRState(t, a.repo, pr.Number, "closed", time.Minute)
	oneComment(t, a, pr.Number, "kardinal closed this PR: it was not merged within waitForMergeTimeout (1m0s)")

	prs := e.WaitPRStatus(t, a.ns, pipelineName, bundle, "prod", closedGrace+2*time.Minute,
		"the PRStatus final-closed after the grace window", func(p *v1alpha1.PRStatus) bool {
			return p.Spec.PRNumber == pr.Number && p.Status.ClosedFinal
		})
	assert.Equal(t, strconv.Itoa(pr.Number), prs.Annotations["kardinal.io/closed-by-kardinal"],
		"the close marked the PRStatus with the PR number")
	framework.Consistently(t, 20*time.Second, "no stopped-tracking comment on the PR kardinal closed", func(context.Context) (bool, string) {
		n := len(e.PRComments(t, a.repo, pr.Number, "kardinal stopped tracking this PR"))
		return n == 0, fmt.Sprintf("%d stopped-tracking comments", n)
	})
	assert.Len(t, e.PRComments(t, a.repo, pr.Number, "kardinal closed this PR"), 1, "PR #%d keeps its one close comment", pr.Number)
	assertEnvAt(t, a, "prod", fixtures.V1)
}
