// TestRenderMergeOptions: the method defaults to merge; the first line of the
// message is the commit title and the rest the body; the PR is in the data.
func TestRenderMergeOptions(t *testing.T) {
	body := prTemplateBody()
	pr := scm.PRTemplatePR{Number: 42, URL: "https://scm/pr/42", Title: "deploy 2.0.0"}

	opts, err := scm.RenderMergeOptions(&v1alpha1.PRMergeConfig{Auto: true}, body, pr)
	require.NoError(t, err)
	assert.Equal(t, scm.MergeOptions{Method: "merge"}, opts)

	opts, err = scm.RenderMergeOptions(&v1alpha1.PRMergeConfig{Auto: true, Method: "squash",
		CommitMessageTemplate: "\n{{ .PR.Title }} (#{{ .PR.Number }})\n\nBundle {{ .Bundle.Name }}\n{{ .PR.URL }}\n"}, body, pr)
	require.NoError(t, err)
	assert.Equal(t, scm.MergeOptions{Method: "squash", CommitTitle: "deploy 2.0.0 (#42)",
		CommitBody: "Bundle web-v2\nhttps://scm/pr/42"}, opts)

	_, err = scm.RenderMergeOptions(&v1alpha1.PRMergeConfig{Auto: true, CommitMessageTemplate: "{{ if false }}x{{ end }}"}, body, pr)
	assert.ErrorContains(t, err, "rendered an empty message")
	_, err = scm.RenderMergeOptions(&v1alpha1.PRMergeConfig{Auto: true, CommitMessageTemplate: "{{ .PR.Nope }}"}, body, pr)
	assert.ErrorContains(t, err, "pr.merge.commitMessageTemplate:")
}

// TestValidatePipelinePR: the Pipeline reconciler and kardinal validate
// render every template with sample data for a promotion and a rollback, so
// a template that only fails for one of them is caught before a Bundle.
//
// Covers SCM-PRCTL-TPL-01.
func TestValidatePipelinePR(t *testing.T) {
	pipeline := func(pr *v1alpha1.PRConfig) *v1alpha1.Pipeline {
		return &v1alpha1.Pipeline{Spec: v1alpha1.PipelineSpec{Environments: []v1alpha1.EnvironmentSpec{
			{Name: "test"}, {Name: "prod", Approval: "pr-review", PR: pr},
		}}}
	}
	tests := []struct {
		name string
		pr   *v1alpha1.PRConfig
		want string
	}{
		{name: "no pr config"},
		{name: "valid", pr: &v1alpha1.PRConfig{TitleTemplate: "{{ .Bundle.Version }}", Labels: []string{"x"},
			Merge: &v1alpha1.PRMergeConfig{Auto: true, CommitMessageTemplate: "{{ .PR.Title }}"}}},
		{name: "parse error", pr: &v1alpha1.PRConfig{BodyTemplate: "{{ if }}"}, want: `environment "prod": pr.bodyTemplate:`},
		{name: "rollback only", pr: &v1alpha1.PRConfig{TitleTemplate: `{{ if .IsRollback }}{{ .Rollback.Nope }}{{ else }}ok{{ end }}`},
			want: `environment "prod": pr.titleTemplate:`},
		{name: "empty for a promotion", pr: &v1alpha1.PRConfig{TitleTemplate: `{{ if .IsRollback }}r{{ end }}`},
			want: "rendered an empty title"},
		{name: "merge message", pr: &v1alpha1.PRConfig{Merge: &v1alpha1.PRMergeConfig{Auto: true, CommitMessageTemplate: "{{ .Nope }}"}},
			want: "pr.merge.commitMessageTemplate:"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := scm.ValidatePipelinePR(pipeline(tt.pr))
			if tt.want == "" {
				assert.NoError(t, err)
				return
			}
			require.Error(t, err)
			assert.Contains(t, err.Error(), tt.want)
		})
	}
}

// TestCheckPRSupport: every control a provider lacks fails the check with
// the field and the provider, and the merge method must be one the provider
// takes.
func TestCheckPRSupport(t *testing.T) {
	providers := map[string]scm.SCMProvider{}
	for _, kind := range []string{"github", "gitlab", "forgejo", "bitbucket", "azuredevops"} {
		p, err := scm.NewProvider(kind, "t", "", "")
		require.NoError(t, err)
		providers[kind] = p
	}
	dyn, err := scm.NewDynamicProvider("gitlab", "t", "", "")
	require.NoError(t, err)
	providers["dynamic gitlab"] = dyn

	auto := func(method, msg string) *v1alpha1.PRConfig {
		return &v1alpha1.PRConfig{Merge: &v1alpha1.PRMergeConfig{Auto: true, Method: method, CommitMessageTemplate: msg}}
	}
	type check struct {
		provider string
		cfg      *v1alpha1.PRConfig
		want     string // "" = supported
	}
	checks := []check{
		{"github", &v1alpha1.PRConfig{Labels: []string{"a"}, Reviewers: []string{"a"}, TeamReviewers: []string{"t"}, Assignees: []string{"a"}}, ""},
		{"github", auto("rebase", "m"), ""},
		{"gitlab", &v1alpha1.PRConfig{Labels: []string{"a"}, Reviewers: []string{"a"}, Assignees: []string{"a"}}, ""},
		{"gitlab", &v1alpha1.PRConfig{TeamReviewers: []string{"t"}}, "pr.teamReviewers is not supported by the gitlab SCM provider"},
		{"gitlab", auto("squash", "m"), ""},
		{"gitlab", auto("rebase", ""), "pr.merge.method rebase is not supported by the gitlab SCM provider"},
		{"dynamic gitlab", auto("rebase", ""), "pr.merge.method rebase is not supported by the gitlab SCM provider"},
		{"forgejo", &v1alpha1.PRConfig{Labels: []string{"a"}, Reviewers: []string{"a"}, TeamReviewers: []string{"t"}, Assignees: []string{"a"}}, ""},
		{"forgejo", auto("", "m"), ""},
		{"bitbucket", &v1alpha1.PRConfig{Reviewers: []string{"{uuid}"}}, ""},
		{"bitbucket", &v1alpha1.PRConfig{Labels: []string{"a"}}, "pr.labels is not supported by the bitbucket SCM provider"},
		{"bitbucket", &v1alpha1.PRConfig{Assignees: []string{"a"}}, "pr.assignees is not supported"},
		{"bitbucket", &v1alpha1.PRConfig{TeamReviewers: []string{"a"}}, "pr.teamReviewers is not supported"},
		{"bitbucket", auto("", ""), "pr.merge.auto is not supported by the bitbucket SCM provider"},
		{"bitbucket", &v1alpha1.PRConfig{Merge: &v1alpha1.PRMergeConfig{}}, ""},
		{"azuredevops", &v1alpha1.PRConfig{Labels: []string{"a"}, Reviewers: []string{"id"}, TeamReviewers: []string{"id"}}, ""},
		{"azuredevops", &v1alpha1.PRConfig{Assignees: []string{"a"}}, "pr.assignees is not supported by the azuredevops SCM provider"},
		{"azuredevops", auto("rebase", "m"), ""},
	}
	for _, c := range checks {
		err := scm.CheckPRSupport(c.cfg, scm.SupportOf(providers[c.provider]))
		if c.want == "" {
			assert.NoError(t, err, "%s %+v", c.provider, c.cfg)
			continue
		}
		if assert.Error(t, err, "%s %+v", c.provider, c.cfg) {
			assert.Contains(t, err.Error(), c.want)
			assert.Contains(t, err.Error(), "docs/scm-providers.md#pr-controls")
		}
	}
	assert.NoError(t, scm.CheckPRSupport(nil, scm.PRSupport{}))
}

// TestPRTemplateData_Bounded: the template data keeps at most 20 images
// and 1024 characters per value, and a list template refuses a value with a
// line break, which would otherwise split into several entries (an author
// "alice\nbob" would assign two users).
//
// Covers SCM-PRCTL-TPL-01.
func TestPRTemplateData_Bounded(t *testing.T) {
	body := prTemplateBody()
	for i := 0; i < 30; i++ {
		body.Bundle.Images = append(body.Bundle.Images, v1alpha1.ImageRef{Repository: fmt.Sprintf("r/i%d", i), Tag: "1"})
	}
	body.Bundle.Provenance.Author = strings.Repeat("a", 2000)
	d := scm.NewPRTemplateData(body)
	assert.Len(t, d.Bundle.Images, 20)
	assert.Equal(t, 1024, len(d.Bundle.Author))

	body = prTemplateBody()
	body.Bundle.Provenance.Author = "alice\nbob"
	_, err := scm.RenderPR(&v1alpha1.PRConfig{Assignees: []string{"{{ .Bundle.Author }}"}}, "t", body)
	assert.ErrorContains(t, err, "pr.assignees: .Bundle.Author has a line break")
	got, err := scm.RenderPR(&v1alpha1.PRConfig{TitleTemplate: "by {{ .Bundle.Author }}"}, "t", body)
	require.NoError(t, err, "a title is one line anyway")
	assert.Equal(t, "by alice bob", got.Title)
}
