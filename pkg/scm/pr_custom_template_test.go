// prTemplateBody is the default body data the pr template tests render for.
func prTemplateBody() scm.PRBody {
	at := metav1.NewTime(time.Date(2026, 3, 4, 5, 6, 0, 0, time.UTC))
	return scm.PRBody{
		PipelineName: "web", Environment: "prod", BundleName: "web-v2",
		Bundle: v1alpha1.BundleSpec{Type: "image",
			Images:     []v1alpha1.ImageRef{{Repository: "ghcr.io/acme/web", Tag: "2.0.0"}},
			Provenance: &v1alpha1.BundleProvenance{Author: "octocat", CommitSHA: "abcdef0123456789", CIRunURL: "https://ci.example/1"}},
		GateResults:          []v1alpha1.GateResult{{GateName: "soak", Result: "Pass", Reason: "a || b", EvaluatedAt: at}},
		UpstreamEnvironments: []scm.PRBodyUpstreamEnv{{Name: "uat", HealthCheckedAt: &at, Elapsed: "30m"}},
	}
}

// TestRenderPR_Defaults: without a pr config, or with an empty one, the PR
// keeps the default title, body and labels.
func TestRenderPR_Defaults(t *testing.T) {
	body := prTemplateBody()
	want, err := scm.RenderPRBody(body)
	require.NoError(t, err)
	for name, cfg := range map[string]*v1alpha1.PRConfig{"nil": nil, "empty": {}} {
		t.Run(name, func(t *testing.T) {
			got, err := scm.RenderPR(cfg, "[kardinal] Promote web-v2 to prod", body)
			require.NoError(t, err)
			assert.Equal(t, "[kardinal] Promote web-v2 to prod", got.Title)
			assert.Equal(t, want, got.Body)
			assert.Empty(t, got.Labels)
			assert.Empty(t, got.Reviewers)
			assert.Empty(t, got.TeamReviewers)
			assert.Empty(t, got.Assignees)
		})
	}
}

// TestRenderPR_Templates covers each template field and the evidence
// functions a custom body keeps the default sections with.
//
// Covers SCM-PRCTL-TPL-01.
func TestRenderPR_Templates(t *testing.T) {
	body := prTemplateBody()
	defaultBody, err := scm.RenderPRBody(body)
	require.NoError(t, err)

	got, err := scm.RenderPR(&v1alpha1.PRConfig{
		TitleTemplate: "deploy {{ .Bundle.Version }}\nto {{ .Environment | upper }} ({{ .Bundle.CommitSHA | truncate 7 }})",
		BodyTemplate:  "Release {{ .Bundle.Name }} by @{{ .Bundle.Author }}\n\n{{ provenanceTable }}\n\n{{ gatesTable }}\n\n{{ upstreamTable }}",
		Labels:        []string{"env/{{ .Environment }}", "{{ range .Bundle.Images }}image/{{ .Tag }}\n{{ end }}", "kardinal", "  ", "env/prod"},
		Reviewers:     []string{"alice", "{{ .Bundle.Author }}"},
		TeamReviewers: []string{"platform"},
		Assignees:     []string{"{{ .Bundle.Author }}", "{{ if .IsRollback }}oncall{{ end }}"},
	}, "default", body)
	require.NoError(t, err)

	assert.Equal(t, "deploy 2.0.0 to PROD (abcdef0)", got.Title, "newlines in a title become spaces")
	assert.True(t, strings.HasPrefix(got.Body, "<!-- kardinal-promoter auto-generated PR -->\nRelease web-v2 by @octocat\n\n### Artifact Provenance\n"), got.Body)
	for _, section := range []string{"### Artifact Provenance", "### Policy Gate Compliance", "### Upstream Verification"} {
		i := strings.Index(defaultBody, section)
		require.GreaterOrEqual(t, i, 0)
		assert.Contains(t, got.Body, section)
	}
	assert.Contains(t, got.Body, `| soak | — | Pass | a \|\| b | 2026-03-04T05:06Z |`, "the gates table escapes cells as the default body does")
	assert.Contains(t, got.Body, "| uat | 2026-03-04T05:06Z | 30m |")
	assert.NotContains(t, got.Body, "Generated by", "only the sections the template asks for")

	assert.Equal(t, []string{"env/prod", "image/2.0.0", "kardinal"}, got.Labels, "one entry per line, blank lines and repeats dropped")
	assert.Equal(t, []string{"alice", "octocat"}, got.Reviewers)
	assert.Equal(t, []string{"platform"}, got.TeamReviewers)
	assert.Equal(t, []string{"octocat"}, got.Assignees, "a template that renders nothing adds nothing")
}

// TestRenderPR_EvidenceFunctions: evidence is the whole default body, and a
// rollback has its heading and notice.
//
// Covers SCM-PRCTL-TPL-01.
func TestRenderPR_EvidenceFunctions(t *testing.T) {
	body := prTemplateBody()
	defaultBody, err := scm.RenderPRBody(body)
	require.NoError(t, err)
	got, err := scm.RenderPR(&v1alpha1.PRConfig{BodyTemplate: "Hello\n{{ evidence }}"}, "t", body)
	require.NoError(t, err)
	assert.Equal(t, "<!-- kardinal-promoter auto-generated PR -->\nHello\n"+defaultBody, got.Body)

	got, err = scm.RenderPR(&v1alpha1.PRConfig{BodyTemplate: "{{ heading }}|{{ rollbackNotice }}|"}, "t", body)
	require.NoError(t, err)
	assert.Equal(t, "<!-- kardinal-promoter auto-generated PR -->\n## Promotion: web-v2 -> web/prod||", got.Body,
		"a promotion has no rollback notice")

	body.RollbackOf, body.RollbackFrom, body.RolledBackBy, body.RestoredVersion = "web-v1", "web-v2", "bob", "1.0.0"
	body.RollbackFromVersion = "2.0.0"
	got, err = scm.RenderPR(&v1alpha1.PRConfig{
		TitleTemplate: "{{ if .IsRollback }}revert {{ .Environment }} to {{ .Rollback.Restores }} ({{ .Rollback.Of }}, by {{ .Rollback.By }}){{ end }}",
		BodyTemplate:  "{{ rollbackNotice }}",
	}, "t", body)
	require.NoError(t, err)
	assert.Equal(t, "revert prod to 1.0.0 (web-v1, by bob)", got.Title)
	assert.Equal(t, "<!-- kardinal-promoter auto-generated PR -->\n"+
		"> **This is a rollback PR.** It restores the images of bundle web-v1 in environment prod.\n"+
		"> Rolling back FROM: web-v2 (2.0.0)\n> Rolling back TO: web-v1 (1.0.0)\n> Rolled back by: bob", got.Body)
}

// TestRenderPR_Errors: a template that does not parse or execute, an empty
// title, and labels the providers refuse are errors naming the field.
//
// Covers SCM-PRCTL-TPL-01.
func TestRenderPR_Errors(t *testing.T) {
	long := strings.Repeat("x", 51)
	tests := []struct {
		name string
		cfg  v1alpha1.PRConfig
		want string
	}{
		{"parse", v1alpha1.PRConfig{TitleTemplate: "{{ .Bundle.Name "}, "pr.titleTemplate:"},
		{"unknown field", v1alpha1.PRConfig{BodyTemplate: "{{ .Bundle.Nope }}"}, "pr.bodyTemplate:"},
		{"unknown function", v1alpha1.PRConfig{Labels: []string{"{{ nope }}"}}, "pr.labels[0]:"},
		{"empty title", v1alpha1.PRConfig{TitleTemplate: "{{ .Bundle.Author | trimPrefix \"octocat\" }}  "}, "pr.titleTemplate: rendered an empty title"},
		{"label too long", v1alpha1.PRConfig{Labels: []string{long}}, "longer than 50 characters"},
		{"label with comma", v1alpha1.PRConfig{Labels: []string{"a,b"}}, "has a comma"},
		{"reviewer error", v1alpha1.PRConfig{Reviewers: []string{"ok", "{{ .X }}"}}, "pr.reviewers[1]:"},
		{"team error", v1alpha1.PRConfig{TeamReviewers: []string{"{{ .X }}"}}, "pr.teamReviewers[0]:"},
		{"assignee error", v1alpha1.PRConfig{Assignees: []string{"{{ .X }}"}}, "pr.assignees[0]:"},
		{"too many entries", v1alpha1.PRConfig{Reviewers: manyReviewers(51)}, "renders 51 entries, more than 50"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			cfg := tt.cfg
			_, err := scm.RenderPR(&cfg, "t", prTemplateBody())
			require.Error(t, err)
			assert.Contains(t, err.Error(), tt.want)
		})
	}
}

// manyReviewers returns n distinct reviewer entries.
func manyReviewers(n int) []string {
	out := make([]string, n)
	for i := range out {
		out[i] = fmt.Sprintf("u%d", i)
	}
	return out
}

// TestPRTemplates_Sandbox: a pr template runs in the controller, so the
// constructs that grow a string without bound or spin are refused when the
// Pipeline is validated and when the step renders it: the 16-byte string
// doubled 24 times through variables (256 MiB), recursion through
// {{template}}, a range over a number, deep ranges, and a string builtin
// fed past its input limit.
//
// Covers SCM-PRCTL-TPL-01.
func TestPRTemplates_Sandbox(t *testing.T) {
	doubling := `{{$a := "xxxxxxxxxxxxxxxx"}}` + strings.Repeat(`{{$a = print $a $a}}`, 24) + `{{$a}}`
	tests := []struct {
		name string
		cfg  v1alpha1.PRConfig
		want string
	}{
		{"doubling body", v1alpha1.PRConfig{BodyTemplate: doubling}, "pr.bodyTemplate: variables are not allowed"},
		{"doubling title", v1alpha1.PRConfig{TitleTemplate: doubling}, "pr.titleTemplate: variables are not allowed"},
		{"doubling label", v1alpha1.PRConfig{Labels: []string{doubling}}, "pr.labels[0]: variables are not allowed"},
		{"doubling message", v1alpha1.PRConfig{Merge: &v1alpha1.PRMergeConfig{Auto: true, CommitMessageTemplate: doubling}},
			"pr.merge.commitMessageTemplate: variables are not allowed"},
		{"recursion", v1alpha1.PRConfig{BodyTemplate: `{{ define "r" }}{{ template "r" }}{{ end }}{{ template "r" }}`}, "pr.bodyTemplate: define and block are not allowed"},
		{"range over a number", v1alpha1.PRConfig{BodyTemplate: `{{ range 100000000 }}{{ end }}`}, "range takes a data path only"},
		{"range over a parenthesised number", v1alpha1.PRConfig{BodyTemplate: `{{ range (1000000000) }}{{ range (1000000000) }}{{ end }}{{ end }}`}, "range takes a data path only"},
		{"range over a function", v1alpha1.PRConfig{BodyTemplate: `{{ range len .Bundle.Name }}{{ end }}`}, "range takes a data path only"},
		{"printf", v1alpha1.PRConfig{TitleTemplate: `{{ printf "%999999999d" 1 }}`}, "printf is not available in this template"},
		{"printf argument indexes", v1alpha1.PRConfig{BodyTemplate: `{{ printf "%[1]s%[1]s%[1]s%[1]s" .Bundle.Name }}`}, "printf is not available in this template"},
		{"replace with an empty old", v1alpha1.PRConfig{TitleTemplate: `{{ replace "" "x" .Bundle.Name }}`}, "replace: the string to replace is empty"},
		{"deep ranges", v1alpha1.PRConfig{BodyTemplate: `{{ range .Bundle.Images }}{{ range $.Bundle.Images }}{{ range $.Bundle.Images }}{{ end }}{{ end }}{{ end }}`},
			"ranges nested more than 2 deep"},
		{"output too long", v1alpha1.PRConfig{TitleTemplate: strings.Repeat("{{ evidence }}", 8)}, "pr.titleTemplate: template output is too large"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			cfg := tt.cfg
			err := scm.ValidatePRConfig(&cfg)
			require.Error(t, err)
			assert.Contains(t, err.Error(), tt.want)
			_, err = scm.RenderPR(&cfg, "t", prTemplateBody())
			if cfg.Merge == nil {
				require.Error(t, err)
				assert.Contains(t, err.Error(), tt.want)
			}
		})
	}
}

