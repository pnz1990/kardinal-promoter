import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const TOKENS_FILE = 'web/tokens/tokens.json'
export const WEB_CSS = 'web/src/styles/tokens.css'
export const WEB_TS = 'web/src/tokens.ts'
export const DOCS_CSS = 'docs/stylesheets/tokens.css'
export const WEB_FONTS = 'web/src/assets/fonts'
export const DOCS_FONTS = 'docs/assets/fonts'
export const PUBLIC_FONTS = 'web/public/fonts'

const BANNER = 'GENERATED by scripts/gen-tokens.mjs from web/tokens/tokens.json — do not edit.'
const LICENSE = ['Copyright 2026 The kardinal-promoter Authors.', 'Licensed under the Apache License, Version 2.0']

// The self-hosted families (web/src/assets/fonts; subset by hack/subset-fonts.sh). Each has a
// metric-adjusted local fallback, so the swap from the fallback moves text as little as possible:
// size-adjust is the width of a sample line against Arial (Courier for the mono), measured with
// fontTools; ascent and descent are the font's own.
export const FONTS = [
  { family: 'Archivo', file: 'Archivo-Variable.woff2', weight: '100 900', stretch: '62% 125%',
    fallback: { local: ['Arial', 'Helvetica', 'Liberation Sans', 'Nimbus Sans'], sizeAdjust: '102.4%', ascent: '86%', descent: '20.5%' } },
  { family: 'Atkinson Hyperlegible Next', file: 'AtkinsonHyperlegibleNext-Variable.woff2', weight: '200 800',
    fallback: { local: ['Arial', 'Helvetica', 'Liberation Sans', 'Nimbus Sans'], sizeAdjust: '100.3%', ascent: '98%', descent: '31.5%' } },
  { family: 'Atkinson Hyperlegible Mono', file: 'AtkinsonHyperlegibleMono-Variable.woff2', weight: '200 800',
    fallback: { local: ['Courier New', 'Courier', 'Liberation Mono', 'Nimbus Mono PS'], sizeAdjust: '105.3%', ascent: '93.5%', descent: '30%' } },
]

// Groups that go to tokens.ts (numbers JS needs). Durations become milliseconds and px
// dimensions become numbers; other dimensions stay strings.
const TS_GROUPS = ['breakpoint', 'container', 'density', 'dur', 'graph', 'layout', 'poll', 'z']

const THEMES = ['light', 'dark']

const isLeaf = (n) => n && typeof n === 'object' && '$value' in n
const isThemed = (v) => v && typeof v === 'object' && !Array.isArray(v) && 'light' in v && 'dark' in v

/** Walks the token tree depth-first, in file order. */
export function flatten(tree, prefix = []) {
  const out = []
  for (const [k, v] of Object.entries(tree)) {
    if (k.startsWith('$')) continue
    if (isLeaf(v)) out.push({ path: [...prefix, k], token: v })
    else if (v && typeof v === 'object') out.push(...flatten(v, [...prefix, k]))
  }
  return out
}

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()

/** The custom property of a token path: color.ink.DEFAULT → --k-ink, graph.station.rFocus → --k-graph-station-r-focus. */
export function cssName(p) {
  const parts = p[0] === 'color' ? p.slice(1) : p
  return '--k-' + parts.filter((s) => s !== 'DEFAULT').map(kebab).join('-')
}

function lookup(tokens, ref) {
  let n = tokens
  for (const k of ref.split('.')) {
    n = n?.[k]
    if (n === undefined) throw new Error(`unknown token reference {${ref}}`)
  }
  if (isLeaf(n)) return n
  if (n && isLeaf(n.DEFAULT)) return n.DEFAULT
  throw new Error(`{${ref}} is not a token`)
}

/** Replaces {a.b} references with var(--k-…). */
function cssValue(v) {
  return String(v).replace(/\{([^}]+)\}/g, (_, ref) => `var(${cssName(ref.split('.'))})`)
}

/** Resolves a token to a literal for one theme (references followed), for the contrast test. */
export function resolve(tokens, ref, theme) {
  const leaf = lookup(tokens, ref)
  let v = leaf.$value
  if (isThemed(v)) v = v[theme]
  const m = typeof v === 'string' && v.match(/^\{([^}]+)\}$/)
  return m ? resolve(tokens, m[1], theme) : v
}

const spaceValue = (n) => (n === 0 ? '0' : `calc(var(--k-density) * ${+(n * 0.25).toFixed(4)}rem)`)

function emits(path, token) {
  if (token.$type === 'number') return token.$extensions?.kardinal?.css === true
  return true
}

function declValue(token) {
  if (token.$type === 'space') return spaceValue(token.$value)
  return cssValue(token.$value)
}

function block(selector, lines, indent = '') {
  return `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join('\n')}\n${indent}}\n`
}

function fontFaces() {
  const out = []
  for (const f of FONTS) {
    const decl = [
      `font-family: "${f.family}";`,
      `src: url("../assets/fonts/${f.file}") format("woff2");`,
      `font-weight: ${f.weight};`,
      ...(f.stretch ? [`font-stretch: ${f.stretch};`] : []),
      'font-style: normal;',
      'font-display: swap;',
    ]
    out.push(block('@font-face', decl))
    const fb = f.fallback
    out.push(block('@font-face', [
      `font-family: "${f.family} Fallback";`,
      `src: ${fb.local.map((l) => `local("${l}")`).join(', ')};`,
      `size-adjust: ${fb.sizeAdjust};`,
      `ascent-override: ${fb.ascent};`,
      `descent-override: ${fb.descent};`,
      'line-gap-override: 0%;',
    ]))
  }
  return out.join('\n')
}

/** Renders the CSS for the web (docs: false) or the docs (docs: true). */
function renderCSS(tokens, { docs }) {
  const all = flatten(tokens).filter(({ path: p, token }) => emits(p, token))
  // A custom property holding var() is resolved on the element that declares it, so every token
  // that refers to a themed one is declared again with each theme: the docs set their scheme on
  // <body>, not on :root.
  const refers = (token) => typeof token.$value === 'string' && token.$value.includes('{')
  const fixed = all.filter(({ token }) => !isThemed(token.$value) && !refers(token))
  const themed = all.filter(({ token }) => isThemed(token.$value))
  const derived = all.filter(({ token }) => !isThemed(token.$value) && refers(token))
  const themeLines = (t) => [
    `color-scheme: ${t};`,
    ...themed.map(({ path: p, token }) => `${cssName(p)}: ${cssValue(token.$value[t])};`),
    ...derived.map(({ path: p, token }) => `${cssName(p)}: ${declValue(token)};`),
    '--k-hatch: repeating-linear-gradient(135deg, var(--k-line) 0 var(--k-space-0_5), transparent var(--k-space-0_5) var(--k-space-1_5));',
  ]

  const lightSel = [':root', '[data-theme="light"]', ...(docs ? ['[data-md-color-scheme="default"]'] : [])].join(', ')
  const darkSel = ['[data-theme="dark"]', ...(docs ? ['[data-md-color-scheme="slate"]'] : [])].join(', ')
  const systemSel = docs ? ':root:not([data-theme]):not([data-md-color-scheme])' : ':root:not([data-theme])'
  const bp = Object.fromEntries(flatten(tokens.breakpoint).map(({ path: p, token }) => [p[0], token.$value]))
  const durs = flatten(tokens.dur).map(({ path: p }) => cssName(['dur', ...p])).filter((n) => n !== '--k-dur-instant')
  const reduced = durs.map((n) => `${n}: 0ms;`)

  const parts = [
    `/*\n * ${LICENSE.join('\n * ')}\n *\n * ${BANNER}\n */\n`,
    fontFaces(),
    block(':root', [
      '--k-density: 1;',
      ...fixed.map(({ path: p, token }) => `${cssName(p)}: ${declValue(token)};`),
      '--k-rail-width: var(--k-layout-rail-collapsed);',
    ]),
    '/* Light: the default, an explicit choice' + (docs ? ', and the docs\' default scheme' : '') + '. */\n' + block(lightSel, themeLines('light')),
    '/* Dark: an explicit choice' + (docs ? ', the docs\' slate scheme,' : '') + ' and the system setting when no choice was made. */\n' + block(darkSel, themeLines('dark')),
    `@media (prefers-color-scheme: dark) {\n${block(systemSel, themeLines('dark'), '  ')}}\n`,
    block('[data-density="compact"]', [`--k-density: ${tokens.density.compact.$value};`]),
    `@media (pointer: coarse) {\n${block(':root', ['--k-control-sm: var(--k-control-lg);', '--k-control-md: var(--k-control-lg);'], '  ')}}\n`,
    `@media (min-width: ${bp.lg}px) {\n${block(':root', ['--k-rail-width: var(--k-layout-rail-expanded);'], '  ')}}\n`,
    `@media (prefers-reduced-motion: reduce) {\n${block(':root', reduced, '  ')}}\n`,
    block('[data-motion="reduce"]', reduced),
  ]
  return parts.join('\n')
}

function tsValue(group, token) {
  const v = token.$value
  if (token.$type === 'duration') return Number.parseFloat(v)
  if (token.$type === 'dimension' && /^-?\d+(\.\d+)?px$/.test(v)) return Number.parseFloat(v)
  return v
}

function tsTree(group, tree) {
  const out = {}
  for (const [k, v] of Object.entries(tree)) {
    if (k.startsWith('$')) continue
    out[k.replace(/-([a-z])/g, (_, c) => c.toUpperCase())] = isLeaf(v) ? tsValue(group, v) : tsTree(group, v)
  }
  return out
}

function tsLiteral(v, indent) {
  if (typeof v !== 'object') return JSON.stringify(v)
  const pad = '  '.repeat(indent + 1)
  const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k))
  return `{\n${Object.entries(v).map(([k, x]) => `${pad}${key(k)}: ${tsLiteral(x, indent + 1)},`).join('\n')}\n${'  '.repeat(indent)}}`
}

function renderTS(tokens) {
  const lines = [
    ...LICENSE.map((l) => `// ${l}`),
    '//',
    `// ${BANNER}`,
    '//',
    '// Durations are in milliseconds and px dimensions are numbers; everything a stylesheet needs is a',
    '// --k-* custom property in styles/tokens.css instead.',
    '',
  ]
  for (const g of TS_GROUPS) {
    lines.push(`export const ${g} = ${tsLiteral(tsTree(g, tokens[g]), 0)} as const`, '')
  }
  return lines.join('\n')
}

/** Renders every generated text file: { relative path → content }. */
export function render(tokens) {
  return {
    [WEB_CSS]: renderCSS(tokens, { docs: false }),
    [WEB_TS]: renderTS(tokens),
    [DOCS_CSS]: renderCSS(tokens, { docs: true }),
  }
}

/** The copied font files: { destination → web/src/assets/fonts source }. The docs get the fonts and
 * their licenses; web/public/fonts gets the licenses, which Vite copies to web/dist next to the
 * hashed fonts. */
export function fontCopies(root = ROOT) {
  const dir = path.join(root, WEB_FONTS)
  const out = {}
  for (const f of fs.readdirSync(dir).sort()) {
    if (/\.(woff2|txt)$/.test(f)) out[path.join(DOCS_FONTS, f)] = path.join(WEB_FONTS, f)
    if (/-OFL\.txt$/.test(f)) out[path.join(PUBLIC_FONTS, f)] = path.join(WEB_FONTS, f)
  }
  return out
}

export function loadTokens(root = ROOT) {
  return JSON.parse(fs.readFileSync(path.join(root, TOKENS_FILE), 'utf8'))
}

function main(argv) {
  const check = argv.includes('--check')
  const files = render(loadTokens())
  const stale = []
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(ROOT, rel)
    const now = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null
    if (now === content) continue
    if (check) stale.push(rel)
    else { fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, content) }
  }
  const copies = fontCopies()
  const want = new Set(Object.keys(copies))
  for (const [dst, src] of Object.entries(copies)) {
    const a = path.join(ROOT, dst)
    const b = fs.readFileSync(path.join(ROOT, src))
    if (fs.existsSync(a) && fs.readFileSync(a).equals(b)) continue
    if (check) stale.push(dst)
    else { fs.mkdirSync(path.dirname(a), { recursive: true }); fs.writeFileSync(a, b) }
  }
  for (const d of [DOCS_FONTS, PUBLIC_FONTS]) {
    const abs = path.join(ROOT, d)
    for (const f of fs.existsSync(abs) ? fs.readdirSync(abs) : []) {
      const rel = path.join(d, f)
      if (want.has(rel)) continue
      if (check) stale.push(`${rel} (not in ${WEB_FONTS})`)
      else fs.rmSync(path.join(ROOT, rel))
    }
  }
  if (check && stale.length) {
    console.error(`design tokens are out of date; run \`make tokens\` (node scripts/gen-tokens.mjs):\n  ${stale.join('\n  ')}`)
    process.exit(1)
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2))
