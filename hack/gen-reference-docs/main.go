// gen-reference-docs writes two generated reference pages:
//
//   - docs/reference/helm-values.md from chart/kardinal-promoter/values.yaml:
//     every value, its default and its "# --" comment;
//   - docs/reference/controller-flags.md from the controller's -help output:
//     every flag, its type, default and help.
//
// With --check it writes nothing and fails when a page differs from what it
// would write, so CI keeps them in sync.
//
//	go run ./hack/gen-reference-docs
//	go run ./hack/gen-reference-docs --check
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"

	yaml "go.yaml.in/yaml/v3"
)

const header = "<!-- GENERATED by hack/gen-reference-docs from %s: do not edit. Run: go run ./hack/gen-reference-docs -->\n\n"

func main() {
	values := flag.String("values", "chart/kardinal-promoter/values.yaml", "the chart's values.yaml")
	helmOut := flag.String("helm-out", "docs/reference/helm-values.md", "the Helm values page")
	flagsOut := flag.String("flags-out", "docs/reference/controller-flags.md", "the controller flags page")
	check := flag.Bool("check", false, "fail when a page is out of date instead of writing it")
	flag.Parse()

	src, err := os.ReadFile(*values)
	if err != nil {
		log.Fatal(err)
	}
	helm, err := HelmValuesPage(src)
	if err != nil {
		log.Fatalf("%s: %v", *values, err)
	}
	help, err := controllerHelp(".")
	if err != nil {
		log.Fatalf("controller -help: %v", err)
	}
	flags := ControllerFlagsPage(help)

	stale := false
	for path, want := range map[string]string{*helmOut: helm, *flagsOut: flags} {
		if *check {
			got, _ := os.ReadFile(path)
			if string(got) != want {
				fmt.Fprintf(os.Stderr, "%s is stale: run go run ./hack/gen-reference-docs\n", path)
				stale = true
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			log.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			log.Fatal(err)
		}
		log.Printf("wrote %s", path)
	}
	if stale {
		os.Exit(1)
	}
}

// ---- Helm values -----------------------------------------------------------

// valueRow is one documented value.
type valueRow struct{ key, def, desc string }

// HelmValuesPage renders values.yaml as a table. A key with a "# --" comment
// is one row, its whole value the default (a map is shown as JSON), unless
// values below it have comments of their own: then it is a section row and
// its values follow. A map without a comment is walked into; a value without
// one is an error, so every value is documented.
func HelmValuesPage(src []byte) (string, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(src, &doc); err != nil {
		return "", err
	}
	if len(doc.Content) != 1 || doc.Content[0].Kind != yaml.MappingNode {
		return "", fmt.Errorf("values.yaml is not a mapping")
	}
	var rows []valueRow
	var undocumented []string
	if err := walkValues(doc.Content[0], "", &rows, &undocumented); err != nil {
		return "", err
	}
	if len(undocumented) > 0 {
		return "", fmt.Errorf("these values have no \"# --\" comment; describe them in values.yaml: %s", strings.Join(undocumented, ", "))
	}
	var b strings.Builder
	fmt.Fprintf(&b, header, "chart/kardinal-promoter/values.yaml")
	b.WriteString("# Helm values\n\n")
	b.WriteString("Every value of the `kardinal-promoter` chart, with its default. Set them with `--set` or a\n")
	b.WriteString("values file; the chart's schema rejects an unknown key. The descriptions are the comments\n")
	b.WriteString("in [values.yaml](https://github.com/pnz1990/kardinal-promoter/blob/main/chart/kardinal-promoter/values.yaml).\n")
	b.WriteString("Where a value sets a controller flag, the flag is in [Controller flags](controller-flags.md).\n\n")
	b.WriteString("| Key | Default | Description |\n|---|---|---|\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", r.key, r.def, cell(r.desc))
	}
	return b.String(), nil
}

func walkValues(m *yaml.Node, prefix string, rows *[]valueRow, undocumented *[]string) error {
	for i := 0; i+1 < len(m.Content); i += 2 {
		k, v := m.Content[i], m.Content[i+1]
		key := k.Value
		if prefix != "" {
			key = prefix + "." + key
		}
		desc, documented := description(k.HeadComment)
		if v.Kind == yaml.MappingNode && len(v.Content) > 0 && (!documented || hasDoc(v)) {
			// A section: its own comment (if any) is a row, then its values.
			if documented {
				*rows = append(*rows, valueRow{key: key, def: "", desc: desc})
			}
			if err := walkValues(v, key, rows, undocumented); err != nil {
				return err
			}
			continue
		}
		if !documented {
			*undocumented = append(*undocumented, key)
			continue
		}
		def, err := defaultValue(v)
		if err != nil {
			return fmt.Errorf("%s: %w", key, err)
		}
		*rows = append(*rows, valueRow{key: key, def: def, desc: desc})
	}
	return nil
}

// hasDoc reports whether a value below m has its own "# --" comment.
func hasDoc(m *yaml.Node) bool {
	for i := 0; i+1 < len(m.Content); i += 2 {
		if _, ok := description(m.Content[i].HeadComment); ok {
			return true
		}
		if v := m.Content[i+1]; v.Kind == yaml.MappingNode && hasDoc(v) {
			return true
		}
	}
	return false
}

// description is the "# --" part of a head comment: from the line that
// starts with "-- " to the end, joined into one paragraph. Comment lines
// before it (a section note) and indented example lines are left out.
func description(head string) (string, bool) {
	lines := strings.Split(head, "\n")
	start := -1
	for i, l := range lines {
		if strings.HasPrefix(strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(l), "#")), "-- ") {
			start = i
		}
	}
	if start < 0 {
		return "", false
	}
	var parts []string
	for i, l := range lines[start:] {
		t := strings.TrimPrefix(strings.TrimSpace(l), "#")
		if i == 0 {
			t = strings.TrimPrefix(strings.TrimSpace(t), "-- ")
		}
		if strings.HasPrefix(t, "   ") { // an indented example: not prose
			continue
		}
		t = strings.TrimSpace(t)
		if t == "" {
			continue
		}
		parts = append(parts, t)
	}
	return strings.Join(parts, " "), true
}

func defaultValue(v *yaml.Node) (string, error) {
	var x any
	if err := v.Decode(&x); err != nil {
		return "", err
	}
	if x == nil {
		return "`null`", nil
	}
	if s, ok := x.(string); ok {
		if s == "" {
			return "`\"\"`", nil
		}
		return "`" + s + "`", nil
	}
	b, err := json.Marshal(x)
	if err != nil {
		return "", err
	}
	return "`" + string(b) + "`", nil
}

// cell makes text safe inside a Markdown table cell.
func cell(s string) string {
	return strings.NewReplacer("|", "\\|", "<", "&lt;", ">", "&gt;").Replace(s)
}

// ---- Controller flags ------------------------------------------------------

// controllerHelp runs the controller in dir with -help, with only the
// variables go needs, and returns what it printed.
func controllerHelp(dir string) (string, error) {
	cmd := exec.Command("go", "run", "./cmd/kardinal-controller", "-help")
	cmd.Dir = dir
	// Only what go needs: a flag's default can come from any variable
	// (KARDINAL_*, GITHUB_APP_*, ...), and the page shows the built-in ones.
	env := []string{}
	for _, kv := range os.Environ() {
		name, _, _ := strings.Cut(kv, "=")
		if name == "PATH" || name == "HOME" || name == "TMPDIR" || strings.HasPrefix(name, "GO") || name == "CGO_ENABLED" {
			env = append(env, kv)
		}
	}
	cmd.Env = env
	var out bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &out
	if err := cmd.Run(); err != nil {
		return "", fmt.Errorf("%w: %s", err, out.String())
	}
	return out.String(), nil
}

var (
	flagLine = regexp.MustCompile(`^  -(\S+)(?: (\S+))?$`)
	defaults = regexp.MustCompile(`\s*\(default (.*)\)$`)
)

// flagRow is one flag.
type flagRow struct{ name, typ, help string }

// ControllerFlagsPage renders the flag package's -help output as a table.
func ControllerFlagsPage(help string) string {
	var rows []flagRow
	for _, l := range strings.Split(help, "\n") {
		if m := flagLine.FindStringSubmatch(l); m != nil {
			typ := m[2]
			if typ == "" {
				typ = "bool"
			}
			rows = append(rows, flagRow{name: m[1], typ: typ})
			continue
		}
		if strings.HasPrefix(l, "    \t") && len(rows) > 0 {
			r := &rows[len(rows)-1]
			r.help = strings.TrimSpace(r.help + " " + strings.TrimSpace(l))
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, header, "the controller's flags (cmd/kardinal-controller)")
	b.WriteString("# Controller flags\n\n")
	b.WriteString("Every flag of `kardinal-controller`. The chart sets them from its values (see\n")
	b.WriteString("[Helm values](helm-values.md)); `controller.extraArgs` passes any other. Defaults are the\n")
	b.WriteString("built-in ones: a flag whose help names a `KARDINAL_*` variable reads it as its default.\n\n")
	b.WriteString("| Flag | Type | Default | Description |\n|---|---|---|---|\n")
	for _, r := range rows {
		def := ""
		if m := defaults.FindStringSubmatch(r.help); m != nil {
			def = "`" + m[1] + "`"
			r.help = strings.TrimSpace(defaults.ReplaceAllString(r.help, ""))
		} else if r.typ == "bool" {
			def = "`false`"
		}
		fmt.Fprintf(&b, "| `--%s` | %s | %s | %s |\n", r.name, r.typ, def, cell(r.help))
	}
	return b.String()
}
